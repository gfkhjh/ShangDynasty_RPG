function makeLesson(modern: string): OracleLesson {
  return SUPPLEMENTAL_LESSONS[modern] ?? lesson(
    `本卡按资料隶定为“${modern}”，具体读义应以同版卜辞为准。`,
    '字形保留甲骨材料的刻写特征；古文字的异体和通假需要结合字例判断。',
    '卜辞涉及祭祀、农事、军事、天象与日常活动，单字须放回完整语境理解。',
  );
}

